#!/usr/bin/env bash
# runsheet_compositional.sh (v15) -- small falsification experiment for the compositional
# race: does each component work, what does the stock Dagster scheduler do with several
# components at once, and do the components generate different exact-search work?
#
# Required:  DAGSTER=/path/to/dagster
#            RAW=/path/to/rXX_gYYYYY.cnf -- a DIMACS CNF exactly as sha1gen wrote it, WITH its
#                "c" comment lines. The tools read variable labels and round/stage markers
#                from those comments, and repair the overstated header themselves. A
#                repaired, comment-stripped CNF is REFUSED (exit 4). The portfolio harness
#                keeps both copies: use cnfs/raw/, not cnfs/solver/, e.g.
#                  RAW=results/tinisat_r20-22/cnfs/raw/r21_g10003.cnf
#                or generate one:
#                  SHA1GEN_PLANTED_OUT=r21_g10003.cnf.planted bin/sha1gen --attack=preimage \
#                    --rounds=21 --hash-bits=160 --seed=10003 --cnf --tseitin-adders > r21_g10003.cnf
#            RAW.planted (optional, next to RAW): the planted message words, one hex word per
#                line, as written by SHA1GEN_PLANTED_OUT; enables the planted-path check.
# Optional:  RANKS (32)  CAP (300 s)  PREFIX (results/comprace)
#            COMPONENTS (direct,low16,staged,part16 -- the reviewed small topology)
#            SCALING_RANKS ("" = skip; e.g. "8 16 32")  REPEATS (5)
#            ALLOW_OVERSUBSCRIBE (0)  -- ranks > cores is refused: rank-scaling on too few
#                                        cores measures CPU sharing, not scheduling
#            ALLOW_STICKY_LOCK (0)    -- refused when workers <= sticky messages (see below)
#            CHECKPOINT_SECS (10)     -- Dagster -v; 0 disables. With -e 0, Dagster writes -o only
#                                        at exit, after EVERY worker has polled, and a mode-4 worker
#                                        cannot poll mid-solve, so a run cut off by the cap can
#                                        leave -o empty after a solution was found. Solutions are
#                                        then recovered from the V4 worker logs, or the latest
#                                        checkpoint (tools/recover_solutions.py), and verified.
#
# Exit codes: 2 build/validation  3 planted-path failure  4 bad environment
#             5 oversubscription refused  6 sticky-lock refused  7 invalid solution
#             8 parser failure  9 a calibration family failed to solve and verify
set -uo pipefail
export LC_ALL=C
# Resolve RAW, DAGSTER and PREFIX against the directory you launched from, BEFORE moving
# to the bundle root, so relative paths mean what they look like.
LAUNCH_DIR=$PWD
absify(){ case "$1" in /*) printf '%s' "$1" ;; *) printf '%s' "$LAUNCH_DIR/$1" ;; esac; }
: "${DAGSTER:?set DAGSTER=/path/to/dagster-executable}"; : "${RAW:?set RAW=/path/to/sha1gen-output.cnf (see header)}"
DAGSTER=$(absify "$DAGSTER"); RAW=$(absify "$RAW")
[[ -n "${PREFIX:-}" ]] && PREFIX=$(absify "$PREFIX")
cd "$(dirname "$0")/.."
if [[ -d "$DAGSTER" ]]; then
  echo "ERROR: DAGSTER=$DAGSTER is a directory. Point it at the built executable," >&2
  echo "       usually ${DAGSTER%/}/dagster (run make in that directory if it is missing)." >&2
  exit 4
fi
[[ -f "$DAGSTER" && -x "$DAGSTER" ]] || { echo "ERROR: DAGSTER=$DAGSTER is not an executable file" >&2; exit 4; }
[[ -r "$RAW" ]] || { echo "ERROR: RAW=$RAW is not readable" >&2; exit 4; }
if ! grep -q -m1 "Instance generated by sha1-sat" "$RAW"; then
  echo "ERROR: RAW=$RAW has no sha1-sat comment lines. It looks like a repaired or foreign CNF." >&2
  echo "       Use sha1gen's own output (the harness's cnfs/raw/ copy, not cnfs/solver/)." >&2
  exit 4
fi
RANKS=${RANKS:-32}; CAP=${CAP:-300}; PREFIX=${PREFIX:-results/comprace}
COMPONENTS=${COMPONENTS:-direct,low16,staged,part16}
SCALING_RANKS=${SCALING_RANKS:-}; REPEATS=${REPEATS:-5}
ALLOW_OVERSUBSCRIBE=${ALLOW_OVERSUBSCRIBE:-0}; ALLOW_STICKY_LOCK=${ALLOW_STICKY_LOCK:-0}
CHECKPOINT_SECS=${CHECKPOINT_SECS:-10}   # Dagster -v: checkpoints keep being written after the
                                         # terminate trigger, so solutions survive a cap kill
mkdir -p "$(dirname "$PREFIX")"; OUT=$(cd "$(dirname "$PREFIX")" && pwd)/$(basename "$PREFIX")
say(){ printf '\n==== %s  [%s]\n' "$*" "$(date -u +%H:%M:%SZ)"; }
now(){ date +%s.%N; }
elapsed(){ awk -v a="$1" -v b="$2" 'BEGIN{printf "%.3f", b-a}'; }
die(){ echo "ERROR: $2" >&2; exit "$1"; }

# ---- cleanup: kill by exact PROCESS NAME. Never `pkill -f dagster`: it matches the
#      invoking shell's own command line whenever that line mentions dagster.
# SESSION-SCOPED cleanup: each Dagster run gets its own session; only that session is signalled.
CURRENT_SID=""
kill_session(){ local x=$1; [[ -n "$x" ]] || return 0; pkill -TERM -s "$x" 2>/dev/null; sleep 2; pkill -KILL -s "$x" 2>/dev/null; return 0; }
cleanup(){ kill_session "$CURRENT_SID"; }
trap cleanup EXIT

# ---- MPI flavour: OpenMPI needs -x to forward environment; MPICH/Hydra forwards by default
MPIV=$(mpirun --version 2>&1 | head -2 | tr '\n' ' ')
if grep -qi "open mpi" <<<"$MPIV"; then
  MPIFWD=(-x GLOG_v -x GLOG_logtostderr -x GLOG_log_dir -x GLOG_logbufsecs)
  OVERSUB=(); [[ "$ALLOW_OVERSUBSCRIBE" == 1 ]] && OVERSUB=(--oversubscribe)
  export OMPI_MCA_btl=${OMPI_MCA_btl:-self,tcp}
  export OMPI_ALLOW_RUN_AS_ROOT=${OMPI_ALLOW_RUN_AS_ROOT:-1} OMPI_ALLOW_RUN_AS_ROOT_CONFIRM=${OMPI_ALLOW_RUN_AS_ROOT_CONFIRM:-1}
else
  MPIFWD=(); OVERSUB=()
fi
CORES=$(nproc)

# run_dagster TAG NRANKS EMODE DAG CNF CAPSEC -> writes $OUT.TAG.{sol,logs/,rc,wall}
# Per-rank glog files (GLOG_log_dir): one shared stderr pipe interleaves long lines.
# GLOG_logbufsecs=0: glog otherwise buffers INFO lines for up to 30 s, and a run stopped
# at the cap loses everything still buffered (measured: a quiet run lost ALL its events).
# At the cap, TERM first, then KILL 10 s later.
# The output file is APPENDED by Dagster, so it is removed first.
run_dagster(){
  local tag=$1 n=$2 e=$3 dag=$4 cnf=$5 cap=$6
  if (( n > CORES )) && [[ "$ALLOW_OVERSUBSCRIBE" != 1 ]]; then
    die 5 "$tag: $n ranks on $CORES cores refused (set ALLOW_OVERSUBSCRIBE=1 only for smoke tests)"
  fi
  rm -rf "$OUT.$tag.logs" "$OUT.$tag.sol" "$OUT.$tag.ck"; mkdir -p "$OUT.$tag.logs" "$OUT.$tag.ck"
  CKPT=(); (( CHECKPOINT_SECS > 0 )) && CKPT=(-v "$CHECKPOINT_SECS" -z "$OUT.$tag.ck/ck")
  local t0 t1 rc
  t0=$(now)
  local sidf="$OUT.$tag.sid"; : > "$sidf"
  GLOG_v=4 GLOG_logtostderr=false GLOG_logbufsecs=0 GLOG_log_dir="$OUT.$tag.logs" \
    setsid bash -c 'echo $$ > "$0"; exec "$@"' "$sidf" timeout -k 10 "$cap" mpirun "${OVERSUB[@]}" -n "$n" "${MPIFWD[@]}" \
    "$DAGSTER" -m 4 -q 2 -b 0 -e "$e" -i 1 "${CKPT[@]}" -o "$OUT.$tag.sol" "$dag" "$cnf" \
    > "$OUT.$tag.mpirun.out" 2>&1 &
  local jp=$!; while [[ ! -s "$sidf" ]]; do sleep 0.05; done; CURRENT_SID=$(cat "$sidf")
  wait "$jp"; rc=$?; t1=$(now)
  kill_session "$CURRENT_SID"; CURRENT_SID=""
  echo "$rc" > "$OUT.$tag.rc"; elapsed "$t0" "$t1" > "$OUT.$tag.wall"
  printf '   %-24s ranks=%-3s -e %s exit=%-3s wall=%ss\n' "$tag" "$n" "$e" "$rc" "$(cat "$OUT.$tag.wall")"
}

# verify_all TAG RAWFILE -> every solution LINE verified independently; fails closed
verify_all(){
  local tag=$1 raw=$2 comps=${3:-$OUT.components.json} src=output
  if [[ ! -s "$OUT.$tag.sol" ]]; then
    rm -rf "$OUT.$tag.recovered"
    python3 tools/recover_solutions.py logs "$OUT.$tag.logs" "$comps" --out-dir "$OUT.$tag.recovered" > "$OUT.$tag.recover.txt" 2>&1
    latest=$(ls -t "$OUT.$tag.ck"/*.check 2>/dev/null | head -1)
    if ! ls "$OUT.$tag.recovered"/*.model >/dev/null 2>&1 && [[ -n "$latest" ]]; then
      python3 tools/recover_solutions.py checkpoint "$latest" "$comps" --out-dir "$OUT.$tag.recovered" >> "$OUT.$tag.recover.txt" 2>&1
    fi
    if ls "$OUT.$tag.recovered"/*.model >/dev/null 2>&1; then
      cat "$OUT.$tag.recovered"/*.model > "$OUT.$tag.sol"; src=recovered
      echo "   -o was empty; recovered $(ls "$OUT.$tag.recovered"/*.model | wc -l) solution(s) from logs/checkpoint"
    fi
  fi
  echo "$src" > "$OUT.$tag.solution_source"
  python3 - "$OUT.$tag.sol" "$raw" "$OUT.$tag.verify.json" <<'PY'
import sys, json, subprocess, tempfile, os
sol, raw, outp = sys.argv[1:4]
lines = [l for l in open(sol)] if os.path.exists(sol) else []
res = []
for i, l in enumerate(lines):
    if not l.strip():
        continue
    with tempfile.NamedTemporaryFile("w", suffix=".m", delete=False) as f:
        f.write(l); p = f.name
    r = subprocess.run([sys.executable, "tools/verify_preimage.py", raw, p], capture_output=True, text=True)
    os.unlink(p)
    ok = r.returncode == 0 and "VALID PREIMAGE" in r.stdout
    res.append({"line": i, "valid": ok})
json.dump({"solutions": len(res), "valid": sum(x["valid"] for x in res), "results": res}, open(outp, "w"), indent=1)
print("   verified %d/%d solution line(s)" % (sum(x["valid"] for x in res), len(res)))
sys.exit(0 if all(x["valid"] for x in res) else 7)
PY
  local rc=$?; (( rc == 0 )) || die 7 "$tag: a reported solution FAILED independent verification"
}

events(){ # events TAG COMPONENTS_JSON
  python3 tools/dagster_events.py "$OUT.$1.logs" "$2" --out "$OUT.$1" > "$OUT.$1.events.txt" \
    || die 8 "$1: event parser failed"
  python3 tools/trace_diversity.py events "$OUT.$1.events.jsonl" --out "$OUT.$1.diversity.json" > /dev/null \
    || die 8 "$1: diversity analysis failed"
  grep -E "events:|never dispatched|first terminal" "$OUT.$1.events.txt" | sed 's/^/   /'
}

# ---------------------------------------------------------------- 0. provenance
say "0. provenance"
python3 - "$OUT.env.json" "$DAGSTER" "$MPIV" "$CORES" <<'PY' || die 4 "provenance failed"
import sys, json, hashlib, platform, socket, subprocess
out, dg, mpiv, cores = sys.argv[1:5]
try:
    import pysat; pv = getattr(pysat, "__version__", "?")
except Exception:
    pv = "missing"
git = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip() or None
json.dump({"hostname": socket.gethostname(), "cores": int(cores), "python": platform.python_version(),
           "pysat": pv, "mpi": mpiv, "dagster": dg,
           "dagster_sha256": hashlib.sha256(open(dg, "rb").read()).hexdigest(), "bundle_git": git},
          open(out, "w"), indent=1)
print("   host %s, %s cores, dagster %s" % (socket.gethostname(), cores, hashlib.sha256(open(dg,'rb').read()).hexdigest()[:16]))
PY

# ---------------------------------------------------------------- 1. build
say "1. build DAG: $COMPONENTS"
python3 tools/compositional_race.py build "$RAW" --out-prefix "$OUT" --components "$COMPONENTS" \
  > "$OUT.build.txt" 2>&1; brc=$?
sed 's/^/   /' "$OUT.build.txt"
(( brc == 0 )) || die 2 "build failed (see $OUT.build.txt); no manifest was written"
python3 -c "import json,sys; e=json.load(open('$OUT.manifest.json'))['validation']['errors']; sys.exit(3 if any('planted' in x for x in e) else (2 if e else 0))"
vrc=$?; (( vrc == 3 )) && die 3 "planted-path check failed"; (( vrc != 0 || brc != 0 )) && die 2 "build or validation failed"
# sticky-message lock: sources and refinement enumerations never complete, so each holds a
# buffer slot for good; the buffer holds one message per worker. If workers <= sticky
# messages, message generation stops permanently (measured). Refinement nodes add one
# sticky message per z8 they are working on, so leave generous headroom.
STICKY=$(python3 -c "import json; r=json.load(open('$OUT.components.json'))['node_roles']; print(sum(1 for v in r.values() if v in ('SOURCE','REFINEMENT','DIRECT_TERMINAL')))")
echo "   sticky messages (sources + refinement + direct): $STICKY; workers at RANKS=$RANKS: $((RANKS-1))"
if (( RANKS - 1 <= 2 * STICKY )) && [[ "$ALLOW_STICKY_LOCK" != 1 ]]; then
  die 6 "workers ($((RANKS-1))) <= 2 x sticky messages ($STICKY): message generation may lock. Raise RANKS or set ALLOW_STICKY_LOCK=1"
fi
# A REFINEMENT node is worse than one sticky message: every incoming z8 that extends
# becomes a never-ending enumeration holding a buffer slot, so given time it fills ANY
# finite buffer and message generation stops (measured: staged alone at 5 ranks and the
# joint/race runs at 20 ranks never dispatched a trace terminal). Recorded, not refused:
# demonstrating it is part of the experiment.
NREF=$(python3 -c "import json; r=json.load(open('$OUT.components.json'))['node_roles']; print(sum(1 for v in r.values() if v=='REFINEMENT'))")
(( NREF > 0 )) && echo "   WARNING: $NREF refinement node(s): under the stock scheduler they eventually lock message generation at any rank count"

# ---------------------------------------------------------------- 2. per-family calibration
say "2. calibration: each component family alone, -e 0, verified"
IFS=',' read -r -a FAMS <<< "$COMPONENTS"
for fam in "${FAMS[@]}"; do
  python3 tools/compositional_race.py build "$RAW" --out-prefix "$OUT.cal_$fam" --components "$fam" \
    > "$OUT.cal_$fam.build.txt" 2>&1 || die 2 "calibration build failed for $fam"
  nn=$(python3 -c "import json; print(len(json.load(open('$OUT.cal_$fam.components.json'))['nodes']))")
  nr=$(( nn + 2 )); (( nr < 3 )) && nr=3        # master + one worker per node + one spare
  run_dagster "cal_$fam" "$nr" 0 "$OUT.cal_$fam.dag" "$OUT.cal_$fam.cnf" "$CAP"
  verify_all "cal_$fam" "$RAW" "$OUT.cal_$fam.components.json"
  events "cal_$fam" "$OUT.cal_$fam.components.json"
  python3 -c "import json,sys; sys.exit(0 if json.load(open('$OUT.cal_$fam.verify.json'))['valid']>0 else 1)" \
    || echo "   NOTE: $fam did not solve within ${CAP}s (recorded, not fatal)"
done

# ---------------------------------------------------------------- 3. joint run, -e 2
say "3. joint run: all components together, -e 2 (one solution per component)"
run_dagster joint "$RANKS" 2 "$OUT.dag" "$OUT.cnf" "$CAP"
verify_all joint "$RAW"
events joint "$OUT.components.json"
echo "   (-e 2 writes solutions only on clean exit; per-component timing comes from events)"

# ---------------------------------------------------------------- 4. race, -e 0
say "4. race: -e 0, first verified preimage from any component ends the job"
run_dagster race "$RANKS" 0 "$OUT.dag" "$OUT.cnf" "$CAP"
verify_all race "$RAW"
events race "$OUT.components.json"

# ---------------------------------------------------------------- 5. offline diversity reference
say "5. offline structural diversity reference (no Dagster)"
python3 tools/trace_diversity.py offline "$RAW" "$OUT.dag" "$OUT.cnf" "$OUT.components.json" \
  --per-source 200 --out "$OUT.diversity_offline.json" > /dev/null || die 8 "offline diversity failed"
python3 -c "
import json; R=json.load(open('$OUT.diversity_offline.json')); J=R['jaccard_t16']
print('   %d comparable pairs, max Jaccard %.4f (near 0 is the NULL expectation)'%(len(J),max(J.values()) if J else 0))
print('   replica test (uncoordinated identical instances):', R.get('replica_test'))"

# ---------------------------------------------------------------- 6. optional repeated scaling
if [[ -n "$SCALING_RANKS" ]]; then
  say "6. scaling: -e 0 race repeated $REPEATS x at ranks {$SCALING_RANKS}"
  for n in $SCALING_RANKS; do
    for rep in $(seq 1 "$REPEATS"); do
      run_dagster "scale_${n}_$rep" "$n" 0 "$OUT.dag" "$OUT.cnf" "$CAP"
      verify_all "scale_${n}_$rep" "$RAW"
    done
  done
  python3 - "$OUT" $SCALING_RANKS <<'PY'
import sys, json, glob, statistics as st
out, ranks = sys.argv[1], sys.argv[2:]
print("   ranks  solved/runs  median wall of solved   (unsolved runs are censored at CAP)")
for n in ranks:
    w, s = [], 0
    for rc in sorted(glob.glob("%s.scale_%s_*.rc" % (out, n))):
        tag = rc[:-3]; v = json.load(open(tag + ".verify.json"))
        if v["valid"] > 0:
            s += 1; w.append(float(open(tag + ".wall").read()))
    runs = len(glob.glob("%s.scale_%s_*.rc" % (out, n)))
    print("   %5s  %4d/%-4d    %s" % (n, s, runs, ("%.1f s" % st.median(w)) if w else "-"))
PY
fi

# ---------------------------------------------------------------- 7. send back
say "7. send-back archive"
# ls -d: plain `ls prefix.*` lists a directory's CONTENTS instead of its name, which
# silently dropped every per-rank log directory from the v15.0 archive.
( cd "$(dirname "$OUT")" && ls -d "$(basename "$OUT")".* | grep -v 'send_back' > "$OUT.archive_list" )
tar czf "$OUT.send_back.tgz" -C "$(dirname "$OUT")" -T "$OUT.archive_list" \
  || die 8 "send-back archive creation failed"
tar tzf "$OUT.send_back.tgz" > "$OUT.archive_contents" || die 8 "send-back archive unreadable"
for d in $(cd "$(dirname "$OUT")" && ls -d "$(basename "$OUT")".*.logs); do
  grep -q "^$d/" "$OUT.archive_contents" || grep -qx "$d/" "$OUT.archive_contents" \
    || die 8 "send-back archive is missing log directory $d"
done
ls -la "$OUT.send_back.tgz" | awk '{print "   "$5" bytes  "$NF}'
echo "   $(wc -l < "$OUT.archive_contents") entries; every run's log directory checked present"
